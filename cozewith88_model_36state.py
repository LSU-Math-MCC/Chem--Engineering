FT3_TO_L = 28.316846592
LITERS_PER_CUBIC_METER = 1000.0
BTU_TO_CAL = 252.164
LB_TO_G = 453.59237
LB_PER_FT3_TO_G_PER_L = LB_TO_G / FT3_TO_L
SECONDS_PER_HOUR = 3600.0


def enthalpy_from_fahrenheit(T_f):
    """Return the supplied enthalpy correlation evaluated at Fahrenheit T.

    The correlation is:

        H = 0.5073*T + 2.047e-4*T**2 + 2.53e-7*T**3

    with T in degrees Fahrenheit and H in Btu/lb. Convert to cal/mol by
    multiplying by BTU_TO_CAL / LB_TO_G * molecular_weight_g_per_mol before
    placing it in ``energy["H"]`` or ``energy["Hfeed"]``.
    """
    T_f = np.asarray(T_f, dtype=float)
    return (
        0.5073 * T_f
        + 2.047e-4 * T_f**2
        + 2.53e-7 * T_f**3
    )


def heat_capacity_from_fahrenheit(T_f):
    """Return the supplied heat-capacity correlation at Fahrenheit T.

    The correlation is:

        Cp = 0.5073 + 4.148e-4*T + 7.590e-7*T**2

    with T in degrees Fahrenheit and Cp in Btu/(lb degree Fahrenheit).
    Convert to cal/mol/degree Fahrenheit by multiplying by
    BTU_TO_CAL / LB_TO_G * molecular_weight_g_per_mol. The energy balance
    expects ``energy["Cp"]`` in cal/mol/degree Celsius, so multiply that
    converted value by 9/5 before placing it there.
    """
    T_f = np.asarray(T_f, dtype=float)
    return 0.5073 + 4.148e-4 * T_f + 7.590e-7 * T_f**2


def stream_density_from_fahrenheit(T_f):
    """Return stream density from the supplied Fahrenheit correlation.

    The correlation is:

        P1 = 1 - (T + 459.67) / 913.68
        P2 = 1 + P1**0.27537
        rho(T) = (3.804 / 0.2641) * P2

    with T in degrees Fahrenheit and rho in lb/ft^3. Convert to g/L with
    ``density_lb_ft3_to_g_l`` before assigning ``rho`` or ``rho_f`` in the
    energy-balance inputs.
    """
    T_f = np.asarray(T_f, dtype=float)
    P1 = 1.0 - (T_f + 459.67) / 913.68
    P2 = 1.0 + P1**0.27537
    return (3.804 / 0.2641) * P2


def density_lb_ft3_to_g_l(rho_lb_ft3):
    """Convert density from lb/ft^3 to g/L."""
    return np.asarray(rho_lb_ft3, dtype=float) * LB_PER_FT3_TO_G_PER_L


def _require_feed(feed):
    """Return all required mf_* feed rates, defaulting unspecified ones to 0."""
    return {name: feed.get(name, 0.0) for name in FEED_NAMES}


def mass_flows_lb_hr_to_mol_hr(mass_flows_lb_hr, molecular_weights_g_per_mol):
    """Convert external mass flows in lb/hr to molar flows in mol/hr."""
    missing_weights = set(mass_flows_lb_hr) - set(molecular_weights_g_per_mol)
    if missing_weights:
        names = ", ".join(sorted(missing_weights))
        raise ValueError(f"Missing molecular weights in g/mol for: {names}.")

    converted_flows = {}
    for name, mass_flow_lb_hr in mass_flows_lb_hr.items():
        molecular_weight = molecular_weights_g_per_mol[name]
        if not np.isfinite(molecular_weight) or molecular_weight <= 0.0:
            raise ValueError(
                f"Molecular weight for {name} must be finite and positive."
            )
        converted_flows[name] = mass_flow_lb_hr * LB_TO_G / molecular_weight

    return converted_flows


def prepare_mass_flow_inputs(mass_flows_lb_hr, molecular_weights_g_per_mol, rho_lb_ft3):
    """Prepare model F and feed values from complete inlet mass flows.

    Every inlet stream in ``mass_flows_lb_hr`` contributes to total volumetric
    flow, including impurities. Species with names in ``FEED_NAMES`` are used
    by the dynamic balances; other species are converted and returned in the
    feed mapping but are not otherwise modeled.
    """
    if not np.isfinite(rho_lb_ft3) or rho_lb_ft3 <= 0.0:
        raise ValueError("rho_lb_ft3 must be finite and positive.")

    mass_flow_values = np.asarray(list(mass_flows_lb_hr.values()), dtype=float)
    if not np.all(np.isfinite(mass_flow_values)) or np.any(mass_flow_values < 0.0):
        raise ValueError("Inlet mass flows must be finite and nonnegative.")

    total_mass_flow_lb_hr = float(np.sum(mass_flow_values))
    F_L_hr = total_mass_flow_lb_hr / rho_lb_ft3 * FT3_TO_L
    feed_mol_hr = mass_flows_lb_hr_to_mol_hr(
        mass_flows_lb_hr,
        molecular_weights_g_per_mol,
    )

    return {"F": F_L_hr, "feed": feed_mol_hr}


def safe_initialize_state(y0=None, *, T0=300.0, min_value=1e-12):
    """Return a numerically safe state vector for the Cozewith 88 model.

    T0 is in degrees Fahrenheit. The supplied model evaluates CAl / CC1 in the
    kinetic bracket of A.61-A.85,
    so CC1 and CAl must both remain strictly positive during integration. This
    helper is a small safeguard for startup conditions and is intentionally
    conservative: it keeps the temperature at T0 and nudges all species/moment
    states away from zero without changing the structure of the original model.
    """
    y = np.zeros(36, dtype=float) if y0 is None else np.asarray(y0, dtype=float).copy()

    if y.size != 36:
        raise ValueError(
            f"safe_initialize_state requires a 36-element state vector; "
            f"received {y.size}."
        )

    y[0] = T0 if np.isfinite(T0) else y[0]
    y[1:] = np.maximum(np.abs(y[1:]), min_value)

    # Prevent the specific zero-division trap in the CAl/CC1 bracket used in A.61-A.85.
    y[4] = max(abs(y[4]), min_value)
    y[7] = max(abs(y[7]), min_value)

    return y


def cozewith88(t, y, p):
    """
    Return dy/dt for the Cozewith 88 model.

    Parameters
    ----------
    t : float
        Time in hours.
    y : array_like, length 36
        State vector in STATE_NAMES order. L200 through L011 are supplied in
        mol/m^3 and converted internally to mol/L; other concentration states
        use mol/L.
    p : dict
        Model parameters.

    Required p entries
    ------------------
    V, F
        Reactor volume in L and outlet volumetric flow in L/hr.
    feed : dict
        Feed molar-flow inputs in mol/hr. For example:
            feed["M1"] = m_f,M1
        Convert external mass flows in lb/hr with
        ``mass_flows_lb_hr_to_mol_hr`` first. Inputs in klb/hr must be
        multiplied by 1000 before conversion.

    kinetic constants appearing in A.54-A.85:
        ki1, ki2, ki3,
        k11, k12, k13, k21, k22, k31,
        kt, kt2, kt3, ktr, ktr1, ktrM2,
        ka, kx, kx2, kx3

    Energy-balance entries from A.50 are discussed below.
    """

    if len(y) != 36:
        raise ValueError(
            f"Cozewith88 requires 36 states; "
            f"received {len(y)}."
        )

    y_internal = np.asarray(y, dtype=float).copy()
    y_internal[24:30] /= LITERS_PER_CUBIC_METER

    (
        T,
        CM1, CM2, CM3, CC1, CC2, CH2, CAl,
        P0, Q0, R0, B0,
        P100, P010, P001,
        Q100, Q010, Q001,
        R100, R010, R001,
        B100, B010, B001,
        L200, L020, L002, L110, L101, L011,
        B200, B020, B002, B110, B101, B011,
    ) = y_internal

    V = p["V"]
    F = p["F"]
    mf = _require_feed(p.get("feed", {}))

    # Kinetic constants
    ki1 = p["ki1"]
    ki2 = p["ki2"]
    ki3 = p["ki3"]
    k11 = p["k11"]
    k12 = p["k12"]
    k13 = p["k13"]
    k21 = p["k21"]
    k22 = p["k22"]
    k31 = p["k31"]
    kt = p["kt"]
    kt2 = p["kt2"]
    kt3 = p["kt3"]
    ktr = p["ktr"]
    ktr1 = p["ktr1"]
    ktrM2 = p["ktrM2"]
    ka = p["ka"]
    kx = p["kx"]
    kx2 = p["kx2"]
    kx3 = p["kx3"]

    # Common bracket appearing repeatedly in A.61-A.85.
    # This is exactly:
    # kt + kt2*CM2 + kt3*CM3 + ktr1*CH2
    # + ktr*(CAl/CC1 - 1) + ktrM2*CM2
    #
    # The source equations contain CAl/CC1, so CC1 must not be zero
    # during integration.
    if CC1 == 0.0:
        raise ZeroDivisionError(
            "CC1 reached zero; the model contains CAl/CC1."
        )

    alkyl_ratio = CAl / CC1 - 1.0

    termination_transfer_rate = (
        kt
        + kt2 * CM2
        + kt3 * CM3
        + ktr1 * CH2
        + ktr * alkyl_ratio
        + ktrM2 * CM2
    )

    d = np.zeros(36)

    # ---------------------------------------------------------------
    # A.54-A.60: Components
    # ---------------------------------------------------------------

    # A.54: ethylene
    RM1 = (
        ki1 * CC2
        + k11 * P0
        + k21 * Q0
        + k31 * R0
    ) * CM1

    d[1] = mf["M1"] / V - F * CM1 / V - RM1

    # A.55: propylene
    RM2 = (
        kx2 * CC1
        + ki2 * CC2
        + k12 * P0
        + k22 * Q0
        + (kt2 + ktrM2) * (P0 + Q0 + R0)
    ) * CM2

    d[2] = mf["M2"] / V - F * CM2 / V - RM2

    # A.56: diene
    RM3 = (
        kx3 * CC1
        + ki3 * P0
        + kt3 * (P0 + Q0 + R0)
    ) * CM3

    d[3] = mf["M3"] / V - F * CM3 / V - RM3

    # Propagation-only monomer consumption rates used by the energy balance.
    RpropM1 = (k11 * P0 + k21 * Q0 + k31 * R0) * CM1
    RpropM2 = (k12 * P0 + k22 * Q0) * CM2
    RpropM3 = k13 * P0 * CM3

    # A.57: inactive catalyst
    d[4] = (
        mf["C1"] / V
        - F * CC1 / V
        - (ka + kx + kx2 * CM2 + kx3 * CM3) * CC1
    )

    # A.58: active catalyst
    d[5] = (
        mf["C2"] / V
        - F * CC2 / V
        + ka * CC1
        - (ki1 * CM1 + ki2 * CM2) * CC2
        + ktr1 * CH2 * (P0 + Q0 + R0)
    )

    # A.59: hydrogen
    d[6] = (
        mf["H2"] / V
        - F * CH2 / V
        - ktr1 * CH2 * (P0 + Q0 + R0)
    )

    # A.60: aluminum alkyl
    d[7] = (
        mf["Al"] / V
        - F * CAl / V
        - ktr * alkyl_ratio * (P0 + Q0 + R0)
    )

    # ---------------------------------------------------------------
    # A.61-A.64: Zeroth moments
    # ---------------------------------------------------------------

    # A.61: ethylene-ended live chains
    d[8] = (
        mf["P0"] / V
        - F * P0 / V
        + ki1 * CM1 * CC2
        + (k21 * Q0 + k31 * R0) * CM1
        - (k12 * CM2 + k13 * CM3) * P0
        - termination_transfer_rate * P0
        - ktr * alkyl_ratio * (Q0 + R0)
    )

    # A.62: propylene-ended live chains
    d[9] = (
        mf["Q0"] / V
        - F * Q0 / V
        + ki2 * CC2 * CM2
        + k12 * CM2 * P0
        - k21 * CM1 * Q0
        - termination_transfer_rate * Q0
        + ktrM2 * CM2 * (P0 + R0)
    )

    # A.63: diene-ended live chains
    d[10] = (
        mf["R0"] / V
        - F * R0 / V
        + ki3 * CM3 * P0
        - k31 * CM1 * R0
        - termination_transfer_rate * R0
    )

    # A.64: dead chains
    d[11] = (
        mf["B0"] / V
        - F * B0 / V
        + termination_transfer_rate * (P0 + Q0 + R0)
    )

    # ---------------------------------------------------------------
    # A.65-A.76: First moments
    # ---------------------------------------------------------------

    # A.65: ethylene in ethylene-ended chains
    d[12] = (
        mf["P100"] / V
        - F * P100 / V
        + ki1 * CC2 * CM1
        + (k11 * P0 + k21 * (Q0 + Q100)
           + k31 * (R0 + R100)) * CM1
        - (k12 * CM2 + k13 * CM3) * P100
        - termination_transfer_rate * P100
        + ktr * alkyl_ratio * (P0 + Q0 + R0)
    )

    # A.66: propylene in ethylene-ended chains
    d[13] = (
        mf["P010"] / V
        - F * P010 / V
        - (k12 * CM2 + k13 * CM3) * P010
        + k21 * CM1 * Q010
        + k31 * CM1 * R010
        - termination_transfer_rate * P010
    )

    # A.67: diene in ethylene-ended chains
    d[14] = (
        mf["P001"] / V
        - F * P001 / V
        - (k12 * CM2 + k13 * CM3) * P001
        + k21 * CM1 * Q001
        + k31 * CM1 * R001
        - termination_transfer_rate * P001
    )

    # A.68: ethylene in propylene-ended chains
    d[15] = (
        mf["Q100"] / V
        - F * Q100 / V
        - k21 * CM1 * Q100
        + k12 * CM2 * P100
        - termination_transfer_rate * Q100
    )

    # A.69: propylene in propylene-ended chains
    d[16] = (
        mf["Q010"] / V
        - F * Q010 / V
        + (ki2 * CC2 + k12 * (P0 + P010) + k22 * Q0) * CM2
        - k21 * CM1 * Q010
        - termination_transfer_rate * Q010
        + ktrM2 * CM2 * (P0 + Q0 + R0)
    )

    # A.70: diene in propylene-ended chains
    d[17] = (
        mf["Q001"] / V
        - F * Q001 / V
        - k21 * CM1 * Q001
        + k12 * CM2 * P001
        - termination_transfer_rate * Q001
    )

    # A.71: ethylene in diene-ended chains
    d[18] = (
        mf["R100"] / V
        - F * R100 / V
        + k13 * CM3 * P100
        - k31 * CM1 * R100
        - termination_transfer_rate * R100
    )

    # A.72: propylene in diene-ended chains
    d[19] = (
        mf["R010"] / V
        - F * R010 / V
        + k13 * CM3 * P010
        - k31 * CM1 * R010
        - termination_transfer_rate * R010
    )

    # A.73: diene in diene-ended chains
    d[20] = (
        mf["R001"] / V
        - F * R001 / V
        + k13 * CM3 * (P0 + P001)
        - k31 * CM1 * R001
        - termination_transfer_rate * R001
    )

    # A.74: ethylene in dead chains
    d[21] = (
        mf["B100"] / V
        - F * B100 / V
        + (
            kt + kt2 * CM2 + kt3 * CM3
            + ktr * alkyl_ratio
            + ktrM2 * CM2
            + ktr1 * CH2
        ) * (P100 + Q100 + R100)
    )

    # A.75: propylene in dead chains
    d[22] = (
        mf["B010"] / V
        - F * B010 / V
        + (
            kt + kt2 * CM2 + kt3 * CM3
            + ktr * alkyl_ratio
            + ktrM2 * CM2
            + ktr1 * CH2
        ) * (P010 + Q010 + R010)
    )

    # A.76: diene in dead chains
    d[23] = (
        mf["B001"] / V
        - F * B001 / V
        + (
            kt + kt2 * CM2 + kt3 * CM3
            + ktr * alkyl_ratio
            + ktrM2 * CM2
            + ktr1 * CH2
        ) * (P001 + Q001 + R001)
    )

    # ---------------------------------------------------------------
    # A.77-A.82: Second moments of live chains
    # ---------------------------------------------------------------

    # A.77: live chains, ethylene/ethylene
    d[24] = (
        mf["L200"] / V
        - F * L200 / V
        + ki1 * CC2 * CM1
        + (
            k11 * (P0 + 2 * P100)
            + k21 * (Q0 + 2 * Q100)
            + k31 * (R0 + 2 * R100)
        ) * CM1
        + ktr * alkyl_ratio * (P0 + Q0 + R0)
        - termination_transfer_rate * L200
    )

    # A.78: live chains, propylene/propylene
    d[25] = (
        mf["L020"] / V
        - F * L020 / V
        + ki2 * CM2 * CC2
        + k12 * (P0 + 2 * P010) * CM2
        + k22 * (Q0 + 2 * Q010) * CM2
        + ktrM2 * CM2 * (P0 + Q0 + R0)
        - termination_transfer_rate * L020
    )

    # A.79: live chains, diene/diene
    d[26] = (
        mf["L002"] / V
        - F * L002 / V
        + k13 * CM3 * (P0 + 2 * P001)
        - termination_transfer_rate * L002
    )

    # A.80: live chains, ethylene/propylene
    d[27] = (
        mf["L110"] / V
        - F * L110 / V
        + (k11 * P010 + k21 * Q010 + k31 * R010) * CM1
        + (k12 * P100 + k22 * Q100) * CM2
        - termination_transfer_rate * L110
    )

    # A.81: live chains, ethylene/diene
    d[28] = (
        mf["L101"] / V
        - F * L101 / V
        + (k11 * P001 + k21 * Q001 + k31 * R001) * CM1
        + k13 * CM3 * P100
        - termination_transfer_rate * L101
    )

    # A.82: live chains, propylene/diene
    d[29] = (
        mf["L011"] / V
        - F * L011 / V
        + (k12 * P001 + k22 * Q001) * CM2
        + k13 * CM3 * P010
        - termination_transfer_rate * L011
    )

    # ---------------------------------------------------------------
    # A.83 onward: Second moments of dead chains
    # ---------------------------------------------------------------

    # A.83: dead chains, ethylene/ethylene
    d[30] = (
        mf["B200"] / V
        - F * B200 / V
        + termination_transfer_rate * L200
    )

    # A.84: dead chains, propylene/propylene
    d[31] = (
        mf["B020"] / V
        - F * B020 / V
        + termination_transfer_rate * L020
    )

    # A.85: dead chains, diene/diene
    d[32] = (
        mf["B002"] / V
        - F * B002 / V
        + termination_transfer_rate * L002
    )

    # User-supplied dead-chain mixed second moments
    # B110: ethylene/propylene
    d[33] = (
        mf["B110"] / V
        - F * B110 / V
        + termination_transfer_rate * L110
    )

    # B101: ethylene/diene
    d[34] = (
        mf["B101"] / V
        - F * B101 / V
        + termination_transfer_rate * L101
    )

    # B011: propylene/diene
    d[35] = (
        mf["B011"] / V
        - F * B011 / V
        + termination_transfer_rate * L011
    )

    # ---------------------------------------------------------------
    # A.50: energy balance
    # ---------------------------------------------------------------
    #
    # The supplied derivation gives:
    #
    # The supplied derivation writes the mixing contribution as Delta H_mix/rho.
    # Here Hmix_cal_per_hr is already a total heat rate, so its contribution is
    # direct, without another density division or time-unit conversion.
    # dT/dt = [F(H_f - H)
    #          + V sum_j R_Mj M_wj (-Delta H_RMj)
    #          + Q_mix] / (V Cp)
    #
    # Here the component-wise forms of F(H_f-H) and Cp are assembled below:
    #   F * sum_i C_i,f (H_i,f - H_i)
    #   Cp = sum_i C_i Cp_i, with Cp_i in cal/(mol degree Celsius)
    # The quotient gives degrees Celsius/hour; convert to the Fahrenheit state
    # basis with 9/5.
    #
    # The source also gives C_C6,f and C_C6 algebraically in A.52-A.53.
    # The thermodynamic property functions/values (H_i, H_i,f, Cp_i,
    # H_mix, rho, molecular weights, etc.) are not defined on the
    # supplied dynamic-model pages, so they are intentionally supplied
    # through p rather than invented here.

    energy = p.get("energy", None)

    if energy is None:
        # If the energy model has not yet been supplied, return NaN for
        # T rather than silently inventing thermodynamic properties.
        d[0] = np.nan
    else:
        # Required energy data/callables:
        #
        # energy["F"]                      optional feed volumetric flow for
        #                                   F(H_f-H); otherwise p["F"] is used.
        # energy["Cfeed"]                  dict of feed concentrations
        # energy["Hfeed"]                  dict of feed enthalpies
        # energy["H"]                      dict/callable current enthalpies
        # energy["Cp"]                     dict/callable heat capacities
        # energy["Mw"]                     dict of molecular weights in g/mol
        # energy["rho"]                    current mixture density in g/L
        # energy["rho_f"]                  feed density in g/L
        # energy["Hmix_cal_per_hr"]        total mixing heat rate, cal/hr
        # energy["minus_dH_cal_per_g"]     reaction heat releases, cal/g
        # energy["Cp_poly"]                polymer heat capacity
        #
        # The keys M1, M2, M3, C6, poly correspond to A.50-A.53.

        F_energy = energy.get("F", F)
        Cfeed = energy["Cfeed"]
        Hfeed = energy["Hfeed"]
        H = energy["H"]
        Cp = energy["Cp"]
        Mw = energy["Mw"]
        rho = energy["rho"]
        rho_f = energy["rho_f"]
        Hmix_cal_per_hr = energy.get("Hmix_cal_per_hr", 0.0)
        minus_dH_cal_per_g = energy["minus_dH_cal_per_g"]

        # A.52: pseudo-component C6 in the feed
        C_C6_f = (
            rho_f
            - (
                Mw["M1"] * Cfeed["M1"]
                + Mw["M2"] * Cfeed["M2"]
                + Mw["M3"] * Cfeed["M3"]
            )
        ) / Mw["C6"]
        Cfeed_for_balance = {**Cfeed, "C6": C_C6_f}

        # A.53: pseudo-component C6 in the reactor.
        # lambda100, lambda010, lambda001 are the total first moments
        # of live + dead chains.
        lam100 = P100 + Q100 + R100 + B100
        lam010 = P010 + Q010 + R010 + B010
        lam001 = P001 + Q001 + R001 + B001

        C_C6 = (
            rho
            - (
                Mw["M1"] * CM1
                + Mw["M2"] * CM2
                + Mw["M3"] * CM3
                + Mw["M1"] * lam100
                + Mw["M2"] * lam010
                + Mw["M3"] * lam001
            )
        ) / Mw["C6"]

        C = {
            "M1": CM1,
            "M2": CM2,
            "M3": CM3,
            "C6": C_C6,
            "poly": energy.get("Cpoly", 0.0),
        }

        # A.50 uses hourly heat rates and a molar basis for the thermal balance:
        #   - C_i are molar concentrations (mol/L)
        #   - Cp_i are molar heat capacities (cal/mol/degree Celsius)
        #   - H_i and Hfeed are molar enthalpies (cal/mol)
        #   - RpropMj are propagation rates (mol/L/hr)
        #   - T is in degrees Fahrenheit and dT/dt is in degrees Fahrenheit/hr.
        #   - reaction heat releases are supplied as -DeltaH in cal/g.
        # If any thermodynamic property is supplied on a mass basis, convert it
        # with the molecular weight before combining with C_i and Cp_i.
        # Sum_i C_i Cp_i in the denominator of A.50.
        denom = sum(C[key] * Cp[key] for key in ["M1", "M2", "M3", "C6", "poly"])

        # Component-wise feed enthalpy, including the C6 solvent pseudo-component.
        feed_term = F_energy * sum(
            Cfeed_for_balance[key] * (Hfeed[key] - H[key])
            for key in ["M1", "M2", "M3", "C6", "poly"]
        )

        reaction_term = V * (
            RpropM1 * Mw["M1"] * minus_dH_cal_per_g["M1"]
            + RpropM2 * Mw["M2"] * minus_dH_cal_per_g["M2"]
            + RpropM3 * Mw["M3"] * minus_dH_cal_per_g["M3"]
        )

        # Feed, reaction, and mixing terms are all heat rates in cal/hr.
        mixing_term = Hmix_cal_per_hr

        d[0] = (
            (feed_term + reaction_term + mixing_term) / (V * denom)
            * 9.0 / 5.0
        )

    d[24:30] *= LITERS_PER_CUBIC_METER
    return d


def integrate_model(params, y0, t_span, t_eval=None, **solve_kwargs):
    """
    Convenience wrapper around scipy.integrate.odeint.

    The ODEINT interface is a good fit for this model because it accepts a full
    time vector in hours directly and keeps the usage simple for feed-sweep and short
    exploratory runs.
    """
    y0 = np.asarray(y0, dtype=float)

    if y0.size != 36:
        raise ValueError(
            f"y0 must contain 36 initial values for the equations supplied; "
            f"received {y0.size}."
        )

    if t_eval is None:
        num_points = int(solve_kwargs.pop("num_points", 101))
        t_eval = np.linspace(float(t_span[0]), float(t_span[1]), num_points)
    else:
        t_eval = np.asarray(t_eval, dtype=float)

    odeint_kwargs = {
        "rtol": solve_kwargs.pop("rtol", 1.0e-5),
        "atol": solve_kwargs.pop("atol", 1.0e-7),
        "hmax": solve_kwargs.pop("max_step", 1.0e-2),
        "mxstep": solve_kwargs.pop("mxstep", 5000),
    }

    # Ignore any solve_ivp-only keywords that are not relevant to odeint.
    for key in list(solve_kwargs.keys()):
        if key not in {"rtol", "atol", "max_step", "mxstep"}:
            solve_kwargs.pop(key)

    try:
        with warnings.catch_warnings():
            warnings.simplefilter("error", ODEintWarning)
            y, info = odeint(
                lambda y, t, p=params: cozewith88(t, y, p),
                y0,
                t_eval,
                args=(params,),
                full_output=True,
                **odeint_kwargs,
            )
    except ODEintWarning as exc:
        raise RuntimeError(f"ODEINT failed: {exc}") from exc

    message = info.get("message", "")
    if message != "Integration successful.":
        raise RuntimeError(f"ODEINT failed: {message}")

    y = np.asarray(y)
    if not np.all(np.isfinite(y)):
        raise RuntimeError("ODEINT failed: non-finite state returned.")

    return t_eval, y


def integrate_interval(params, y0, dt, t0=0.0, **solve_kwargs):
    """Integrate over one closed interval [t0, t0 + dt].

    The returned time vector contains the two interval endpoints.
    """
    if dt <= 0.0:
        raise ValueError(f"dt must be positive; received {dt!r}.")

    return integrate_model(
        params,
        y0,
        (t0, t0 + dt),
        t_eval=np.array([t0, t0 + dt]),
        **solve_kwargs,
    )


def integrate_piecewise(
    params,
    y0,
    dt,
    n_steps,
    *,
    t0=0.0,
    control_update=None,
    **solve_kwargs,
):
    """Integrate repeatedly over [t, t+dt] and update controls between chunks.

    Parameters
    ----------
    params : dict
        Base model parameters.
    y0 : array_like, shape (36,)
        Initial condition for the first chunk.
    dt : float
        Duration of each integration interval.
    n_steps : int
        Number of chunks to integrate.
    t0 : float, optional
        Starting time of the first interval.
    control_update : callable, optional
        Function with signature control_update(step, t, y, params) -> updated_params.
        It is called before each chunk is integrated so feed and control values can
        be adjusted for each interval.
    **solve_kwargs
        Passed to integrate_model / odeint.

    Returns
    -------
    t_hist : ndarray, shape (n_steps + 1,)
        Times including the initial condition and every interval endpoint.
    y_hist : ndarray, shape (n_steps + 1, 36)
        State history across all chunks.
    """
    if dt <= 0.0:
        raise ValueError(f"dt must be positive; received {dt!r}.")
    if n_steps < 1:
        raise ValueError(f"n_steps must be >= 1; received {n_steps!r}.")

    current_t = float(t0)
    current_y = np.asarray(y0, dtype=float).copy()

    t_hist = [current_t]
    y_hist = [current_y.copy()]

    for step in range(n_steps):
        step_params = deepcopy(params)
        if control_update is not None:
            step_params = control_update(step, current_t, current_y, step_params)

        t_chunk, y_chunk = integrate_interval(
            step_params,
            current_y,
            dt,
            t0=current_t,
            **solve_kwargs,
        )

        current_t = float(t_chunk[-1])
        current_y = np.asarray(y_chunk[-1], dtype=float).copy()

        t_hist.append(current_t)
        y_hist.append(current_y.copy())

    return np.asarray(t_hist, dtype=float), np.asarray(y_hist, dtype=float)


